-- PART A

-- A1: Store ranks with unique names and levels from 1 to 6.
CREATE TABLE ranks (
    rank_id INT PRIMARY KEY,
    rank_name VARCHAR(50) NOT NULL UNIQUE,
    rank_level INT NOT NULL,
    CHECK (rank_level BETWEEN 1 AND 6)
);

-- A2: Store each unit and its location.
CREATE TABLE units (
    unit_id INT PRIMARY KEY,
    unit_name VARCHAR(80) NOT NULL UNIQUE,
    location VARCHAR(80) NOT NULL
);

-- A3: An ongoing mission has a NULL end date.
CREATE TABLE missions (
    mission_id INT PRIMARY KEY,
    mission_name VARCHAR(100) NOT NULL UNIQUE,
    start_date DATE NOT NULL,
    end_date DATE,
    CHECK (end_date IS NULL OR end_date >= start_date)
);

-- A4: Store soldiers and connect each soldier to a rank and a unit.
CREATE TABLE soldiers (
    soldier_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_number VARCHAR(60) NOT NULL UNIQUE,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    date_of_birth DATE NOT NULL,
    enlistment_date DATE NOT NULL,
    status VARCHAR(10) NOT NULL DEFAULT 'Active',
    rank_id INT NOT NULL,
    unit_id INT NOT NULL,
    CHECK (status IN ('Active', 'On Leave', 'Retired')),
    CHECK (enlistment_date > date_of_birth),
    FOREIGN KEY (rank_id) REFERENCES ranks(rank_id),
    FOREIGN KEY (unit_id) REFERENCES units(unit_id)
);

-- A5: The two-column key prevents duplicate mission assignments.
CREATE TABLE soldier_missions (
    soldier_id INT NOT NULL,
    mission_id INT NOT NULL,
    mission_role VARCHAR(60) NOT NULL,
    PRIMARY KEY (soldier_id, mission_id),
    FOREIGN KEY (soldier_id) REFERENCES soldiers(soldier_id),
    FOREIGN KEY (mission_id) REFERENCES missions(mission_id)
);

